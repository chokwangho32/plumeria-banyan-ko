let currentLang = 'ko';

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (lang !== 'ko' && lang !== 'en') return;
  currentLang = lang;
  localStorage.setItem('pvr_lang', lang);
  updateDOM();
}

export function initI18n() {
  const saved = localStorage.getItem('pvr_lang');
  if (saved) {
    currentLang = saved;
  }
  updateDOM();

  const langBtn = document.getElementById('langToggleBtn');
  if (langBtn) {
    langBtn.addEventListener('click', () => {
      setLang(currentLang === 'ko' ? 'en' : 'ko');
    });
  }
}

function updateDOM() {
  const texts = i18nData[currentLang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (texts[key]) {
      el.innerHTML = texts[key];
    }
  });

  const langBtn = document.getElementById('langToggleBtn');
  if (langBtn) {
    langBtn.innerHTML = currentLang === 'ko' ? '🇺🇸 <span class="lang-label">English</span>' : '🇰🇷 <span class="lang-label">한국어</span>';
  }
  document.documentElement.lang = currentLang;
}
